"""Dataset statistics table: event logs, split into the pre-training corpus and the held-out evaluation logs.

Reads results/log_stats.csv, written by scripts/log_stats.py, which measures every column on the RAW
logs (activity = concept:name) before prefix extraction or trace-length filtering. Within each
block the rows are ordered by number of cases, largest first.

Columns beyond the previous version of this table, named and defined as in the predictive-process-
monitoring benchmarks (Rama-Maneiro et al., IEEE TSC; Verenich et al., ACM TIST), which report the
MEAN of both, in days:
  * Event duration -- mean over all consecutive event pairs within a case of t_{i+1} - t_i, in days
                      (events sorted by timestamp within the case, so no interval is negative)
  * Case duration  -- mean over cases of t_last - t_first, in days: how long a case takes end to end
Means (not medians) so that shared logs can be checked line by line against those benchmarks; this
script reproduces their published BPI12 (0.45 / 8.62), BPI13-incidents (1.57 / 12.08) and
Road Traffic (341.68) values exactly.

#Var. is counted in file order, the convention that reproduces the previously published counts.
Writes figures/datasets_table.tex.
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)   # repo root
STATS = os.path.join(ROOT, "results", "log_stats.csv")

DOMAIN = {"BPI12": "Finance", "BPI17": "Finance", "BPI19": "Procurement", "BPI18": "Government",
          "Road Traffic": "Government", "BPI20ID": "Travel", "BPI11": "Healthcare",
          "Hospital Billing": "Healthcare", "MIMIC": "Healthcare", "BPI13": "IT service",
          "Helpdesk": "IT service"}
# BPI12 is pretrained on AND used as the in-domain evaluation reference; it gets one row, in the
# pre-training block, flagged by a dagger.
BOTH = "BPI12"


def num(v):
    """Two decimals for both duration columns, as in the benchmark tables."""
    return "%.2f" % float(v)


rows = list(csv.DictReader(open(STATS)))
pre = sorted([r for r in rows if r["split"] in ("pre", "both")], key=lambda r: -int(r["cases"]))
ev = sorted([r for r in rows if r["split"] == "eval"], key=lambda r: -int(r["cases"]))

L = [r"% " + "=" * 76,
     r"%  Event logs and raw-log statistics. Requires: booktabs, multirow, graphicx.",
     r"%  Generated by figures/make_datasets_table.py from results/log_stats.csv",
     r"%  (data/log_stats.py). Do not edit by hand.",
     r"% " + "=" * 76,
     r"\begin{table}[t]", r"\centering",
     r"\caption{Event logs used in this work with raw-log statistics, split into the pre-training "
     r"corpus and the held-out evaluation logs and ordered by size within each block. \#Act.\ is the "
     r"number of distinct activities (\texttt{concept:name}); Med./Max are the case length in events; "
     r"\#Var.\ is the number of distinct control-flow variants; \emph{event duration} is the mean time "
     r"between two consecutive events of a case and \emph{case duration} the mean time from a case's "
     r"first to its last event, both in days, following the reporting convention of the "
     r"predictive-process-monitoring benchmarks. All statistics are measured on the raw logs, before "
     r"prefix extraction and trace-length filtering. $\dagger$~BPI12 is pre-trained on and also serves "
     r"as the in-domain evaluation reference. The corpus spans finance, government, healthcare and "
     r"IT-service domains and roughly three orders of magnitude in size. The two duration columns are "
     r"as heterogeneous: mean event duration ranges from about eleven hours (BPI12) to four months "
     r"(Road Traffic), and mean case duration from five days (MIMIC) to more than a year (BPI11).}",
     r"\label{tab:datasets}",
     r"\small\setlength{\tabcolsep}{4pt}",
     r"\begin{tabular}{@{}cll rrr rr r rr@{}}", r"\toprule",
     r"& Dataset & Domain & \#Cases & \#Events & \#Act. & \multicolumn{2}{c}{Trace len.} & \#Var. "
     r"& \multicolumn{2}{c}{Mean duration (days)} \\",
     r"\cmidrule(lr){7-8}\cmidrule(l){10-11}",
     r" & & & & & & Med. & Max & & Event & Case \\", r"\midrule"]

# The block name is a rotated \multirow cell in a leading column, vertically centred on its rows.
# Two stacked words keep the rotated label shorter than the block is tall.
for label, block in ((r"\shortstack{Pre-training\\corpus}", pre),
                     (r"\shortstack{Held-out\\evaluation}", ev)):
    if block is ev:
        L.append(r"\cmidrule(l){2-11}")
    tag = r"\multirow{%d}{*}{\rotatebox[origin=c]{90}{\footnotesize %s}}" % (len(block), label)
    for i, r in enumerate(block):
        name = r["name"] + (r"$^{\dagger}$" if r["name"] == BOTH else "")
        L.append("%s & %-26s & %-11s & %s & %s & %s & %s & %s & %s & %s & %s \\\\" % (
            tag if i == 0 else "", name, DOMAIN[r["name"]], format(int(r["cases"]), ","),
            format(int(r["events"]), ","), r["acts"], r["med_len"], format(int(r["max_len"]), ","),
            format(int(r["variants_fileorder"]), ","), num(r["mean_gap"]), num(r["mean_dur"])))
L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]

out = os.path.join(HERE, "datasets_table.tex")   # beside the other generated tables (docs/ is not in the repo)
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(L))
print("\nwrote", out)
